HEADERS_ZH = {
    "section": "章节",
    "seq": "序号",
    "item_name": "项目名称",
    "spec": "规格/套数",
    "unit_price": "单价(印刷/标准)",
    "unit_price_alt": "单价(手写/执行)",
    "packaging": "包装材料",
    "remark": "备注",
    "page": "PDF页",
}


def write_sheet(ws, meta: dict) -> None:
    header_fill = PatternFill("solid", fgColor="E8F0FE")
    bold = Font(bold=True)
    ws.append(["客户代码", meta["code"]])
    ws.append(["医院名称", meta["name"]])
    ws.append(["源PDF", meta["pdf"]])
    if meta.get("note"):
        ws.append(["审阅说明", meta["note"]])
    ws.append([])
    ws.append([HEADERS_ZH[c] for c in COLUMNS])
    for cell in ws[ws.max_row]:
        cell.font = bold
        cell.fill = header_fill
    for row in meta["rows"]:
        ws.append(list(row))
    for col in range(1, len(COLUMNS) + 1):
        ws.column_dimensions[get_column_letter(col)].width = 18
    for row in ws.iter_rows(min_row=1, max_row=ws.max_row):
        for cell in row:
            cell.alignment = Alignment(wrap_text=True, vertical="top")


def write_markdown(path: Path, meta: dict) -> None:
    lines = [
        f"# {meta['name']}（{meta['code']}）价目审阅表",
        "",
        f"- **源 PDF**：`backend/src/main/resources/clerk-rules/attachments/{meta['pdf']}`",
        f"- **生成方式**：扫描件视觉识别 + 人工结构化（供审阅校对）",
    ]
    if meta.get("note"):
        lines.append(f"- **说明**：{meta['note']}")
    lines.extend(["", "| " + " | ".join(HEADERS_ZH[c] for c in COLUMNS) + " |", "| " + " | ".join(["---"] * len(COLUMNS)) + " |"])
    for row in meta["rows"]:
        cells = [str(v) if v != "" else "" for v in row]
        lines.append("| " + " | ".join(cells) + " |")
    lines.extend([
        "",
        "## 页图参考",
        "",
        "对应 PNG 位于 `docs/clerk-price-lists/_pages/`：",
        f"- `{meta['code']}_p*.png`",
        "",
        "> 如发现识别误差，请直接在本表或 Excel 中标注后反馈，再写入 `SEPARATE_PRICING_SYSTEM.priceTable[]`。",
    ])
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    combined = Workbook()
    combined.remove(combined.active)
    index = ["# 内勤规则 PDF 价表审阅包", "", "由 `scripts/build_clerk_price_list_review.py` 生成。", ""]
    for code, meta in HOSPITALS.items():
        slug = f"{code}-{meta['name']}"
        xlsx_path = OUT / f"{slug}.xlsx"
        md_path = OUT / f"{slug}.md"
        wb = Workbook()
        ws = wb.active
        ws.title = code[:31]
        write_sheet(ws, meta)
        wb.save(xlsx_path)
        write_markdown(md_path, meta)
        cws = combined.create_sheet(title=code[:31])
        write_sheet(cws, meta)
        index.append(f"- [{meta['name']}]({slug}.md) · [Excel]({slug}.xlsx)")
    combined.save(OUT / "clerk-price-lists-all.xlsx")
    index.extend([
        "",
        "## 合并 Excel",
        "",
        "- [clerk-price-lists-all.xlsx](clerk-price-lists-all.xlsx)（4 个 sheet）",
        "",
        "## 特别说明",
        "",
        "- **太平人民医院**：PDF 含大量手写改价，Excel 中 `单价(手写/执行)` 列优先采信。",
        "- **南岗妇产**：按器械包名+套数定价，与前三家通用价目表结构不同。",
        "- **道外/三精**：为标准铂康通用价目结构，可作对照基线。",
    ])
    (OUT / "README.md").write_text("\n".join(index), encoding="utf-8")
    manifest = {code: {"name": m["name"], "row_count": len(m["rows"]), "pdf": m["pdf"]} for code, m in HOSPITALS.items()}
    (OUT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {len(HOSPITALS)} hospitals to {OUT}")


if __name__ == "__main__":
    main()
